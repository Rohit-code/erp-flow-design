// Mock order/booking records — one per row in OrderList, each with its own
// full audit trail instead of every row opening the same hardcoded timeline.
//
// Every record also carries a `snapshot` — a read-only mirror of the shape
// BookingContext keeps for the live booking (depot replies, containers, CRO,
// KYC, BL, invoice, MBL) — so screens across Ops, Depot and the Customer
// Portal can show the full range of real cases (multi-depot pick, food-grade
// hold, standing credit vs pay-before-MBL, a shut-out container, KYC
// rejection, a BL change-request) without inventing a second booking engine.
// The live booking (BKG-2024-00142) still writes its own history through
// BookingContext; every other record here is a static, already-resolved case.

export type TimelineEntry = {
  id: string
  label: string
  actor: string
  role: string
  ts: string
  status: 'done' | 'active' | 'pending'
  note?: string
  icon: string
}

export type CaseContainer = {
  number: string
  status: 'depot-in' | 'depot-out'
  gatedIn: boolean
  sob: boolean
  sobDate: string | null
  cleanCertified: boolean
  cleanCertifiedBy: string | null
}

export type CaseSnapshot = {
  /** The rate the customer accepted — null if a rate was never agreed. */
  agreedRate: number | null
  foodGrade: boolean
  requirementSent: boolean
  depotReplies: Record<string, 'pending' | 'yes' | 'no'>
  depotId: string | null
  containersExpected: string[]
  containers: CaseContainer[]
  croId: string | null
  kycStatus: 'not-started' | 'submitted' | 'approved' | 'rejected'
  kycRejectionReason: string | null
  blStatus: 'none' | 'drafted' | 'changes-requested' | 'approved'
  blChangeNote: string | null
  mblType: 'surrender' | 'original' | null
  invoiceReleased: boolean
  hasStandingCredit: boolean
  paymentStatus: 'unpaid' | 'standing-credit' | 'paid'
  mblReleased: boolean
}

export type OrderRecord = {
  id: string
  customer: string
  pol: string
  pod: string
  equipment: string
  statusLabel: string
  statusVariant: 'active' | 'in-progress' | 'cancelled'
  timeline: TimelineEntry[]
  snapshot: CaseSnapshot
}

